CREATE TABLE IF NOT EXISTS series (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner VARCHAR(160) NOT NULL,
 name VARCHAR(200) NOT NULL,
 author VARCHAR(200) NOT NULL DEFAULT '',
 language VARCHAR(8) NOT NULL DEFAULT 'fr',
 followed BOOLEAN NOT NULL DEFAULT 1,
 checked_at DATETIME NULL,
 attempted_at DATETIME NULL,
 check_error VARCHAR(300) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY owner_series(owner,name,author), INDEX followed_series(owner,followed)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
ALTER TABLE series ADD COLUMN IF NOT EXISTS description TEXT NULL;
CREATE TABLE IF NOT EXISTS book (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner VARCHAR(160) NOT NULL,
 google_id VARCHAR(100) NULL,
 title VARCHAR(250) NOT NULL,
 authors VARCHAR(500) NOT NULL DEFAULT '',
 description TEXT NOT NULL,
 isbn VARCHAR(20) NOT NULL DEFAULT '',
 publisher VARCHAR(200) NOT NULL DEFAULT '',
 published VARCHAR(30) NOT NULL DEFAULT '',
 language VARCHAR(8) NOT NULL DEFAULT 'fr',
 genre VARCHAR(120) NOT NULL DEFAULT '',
 format VARCHAR(12) NOT NULL DEFAULT 'paper',
 unit VARCHAR(12) NOT NULL DEFAULT 'pages',
 total DECIMAL(10,2) NULL,
 owned BOOLEAN NOT NULL DEFAULT 0,
 series_id INT UNSIGNED NULL,
 volume DECIMAL(6,2) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY owner_google_format(owner,google_id,format), INDEX owner_book(owner),
 FOREIGN KEY(series_id) REFERENCES series(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
ALTER TABLE book
 ADD COLUMN IF NOT EXISTS subtitle VARCHAR(250) NOT NULL DEFAULT '',
 ADD COLUMN IF NOT EXISTS page_count INT UNSIGNED NULL,
 ADD COLUMN IF NOT EXISTS release_date VARCHAR(30) NOT NULL DEFAULT '',
 ADD COLUMN IF NOT EXISTS preorder BOOLEAN NOT NULL DEFAULT 0,
 ADD COLUMN IF NOT EXISTS read_override BOOLEAN NULL;
CREATE TABLE IF NOT EXISTS reading (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 book_id INT UNSIGNED NOT NULL,
 status VARCHAR(12) NOT NULL DEFAULT 'to_read',
 position DECIMAL(10,2) NOT NULL DEFAULT 0,
 started DATE NULL,
 finished DATE NULL,
 rating TINYINT UNSIGNED NULL,
 notes TEXT NOT NULL,
 review TEXT NOT NULL,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(book_id) REFERENCES book(id) ON DELETE CASCADE, INDEX book_reading(book_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS progress (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 reading_id INT UNSIGNED NOT NULL,
 position DECIMAL(10,2) NOT NULL,
 recorded_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(reading_id) REFERENCES reading(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS suggestion (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 series_id INT UNSIGNED NOT NULL,
 fingerprint CHAR(64) NOT NULL,
 google_id VARCHAR(100) NOT NULL,
 title VARCHAR(250) NOT NULL,
 authors VARCHAR(500) NOT NULL DEFAULT '',
 published VARCHAR(30) NOT NULL DEFAULT '',
 language VARCHAR(8) NOT NULL DEFAULT '',
 volume DECIMAL(6,2) NULL,
 reason VARCHAR(250) NOT NULL,
 state VARCHAR(12) NOT NULL DEFAULT 'pending',
 discovered_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY series_candidate(series_id,fingerprint),
 FOREIGN KEY(series_id) REFERENCES series(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
ALTER TABLE suggestion ADD COLUMN IF NOT EXISTS preorder BOOLEAN NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS api_cache (
 cache_key CHAR(64) PRIMARY KEY, payload MEDIUMTEXT NOT NULL, expires_at DATETIME NOT NULL,
 INDEX cache_expiry(expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS oidc_logout (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, subject VARCHAR(250) NOT NULL,
 sid VARCHAR(250) NULL, issued_at BIGINT NOT NULL,
 UNIQUE KEY logout_identity(subject,sid), INDEX logout_subject(subject)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
